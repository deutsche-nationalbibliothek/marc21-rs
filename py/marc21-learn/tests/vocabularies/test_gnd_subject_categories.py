def test_default() -> None:
    """Test the `gnd_subject_categories` function without params."""
    # check for completnes
    gnd_sc = gnd_subject_categories()
    assert gnd_sc.height == 412
    assert gnd_sc.width == 4

    # check for uniqueness
    for notation in GND_SUBJECT_CATEGORIES:
        assert gnd_sc.filter(pl.col("notation") == notation).height == 1

    assert "label_de" in gnd_sc
    assert "label_en" in gnd_sc


def test_language() -> None:
    """Test the `gnd_subject_categories` function without params."""
    gnd_sc = gnd_subject_categories(language="de")
    assert gnd_sc.height == 412
    assert gnd_sc.width == 3
    assert "label" in gnd_sc

    gnd_sc = gnd_subject_categories(language="en")
    assert gnd_sc.height == 412
    assert gnd_sc.width == 3
    assert "label" in gnd_sc


def test_normalize() -> None:
    """Test the normalize parameter."""
    # test that result is NFC encoded
    lhs = gnd_subject_categories(language="de").with_columns(
        pl.col("label").str.len_bytes().alias("len"),
    )
    assert lhs.height == 412
    assert lhs.width == 4

    rhs = gnd_subject_categories(language="de", normalize="NFC").with_columns(
        pl.col("label").str.len_bytes().alias("len"),
    )
    assert rhs.height == 412
    assert rhs.width == 4

    assert (
        lhs.join(rhs, on="notation", how="inner")
        .filter(pl.col("len") != pl.col("len_right"))
        .is_empty()
    )

    # NFC
    df = gnd_subject_categories(language="de", normalize="NFC").with_columns(
        pl.col("label").str.len_bytes().alias("len"),
    )
    assert df.height == 412
    assert df.width == 4

    assert (
        df.filter(pl.col("notation") == "00")
        .filter(pl.col("len") == 30)
        .height
        == 1
    )

    # NFD
    df = gnd_subject_categories(language="de", normalize="NFD").with_columns(
        pl.col("label").str.len_bytes().alias("len"),
    )
    assert df.height == 412
    assert df.width == 4

    assert (
        df.filter(pl.col("notation") == "00")
        .filter(pl.col("len") == 31)
        .height
        == 1
    )
